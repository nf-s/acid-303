const curve = (values: number[], base = 0, multiply = false) =>
  Array.from({ length: STEP_COUNT }, (_, index) =>
    Math.max(
      0,
      Math.min(
        1,
        multiply
          ? base * (values[index % values.length] ?? 1)
          : base + (values[index % values.length] ?? 0),
      ),
    ),
  );

